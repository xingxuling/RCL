import {
  extractCapabilitiesFromJsonSchema,
  extractCapabilitiesFromOpenApi,
  extractCapabilitiesFromSqlDdl,
} from '../src/source-capability-frontends.mjs';

const schemaBundle = extractCapabilitiesFromJsonSchema({
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'https://taowind.example/contracts/device-node',
  title: 'DeviceNode',
  type: 'object',
  required: ['id', 'kind', 'online'],
  additionalProperties: false,
  properties: {
    id: { type: 'string', minLength: 1 },
    kind: { enum: ['vision', 'dialogue', 'control'] },
    online: { type: 'boolean' },
  },
});

const openApiBundle = extractCapabilitiesFromOpenApi({
  openapi: '3.1.2',
  info: { title: 'Distributed Dialogue Node API', version: '0.1.0' },
  paths: {
    '/nodes/{nodeId}/status': {
      get: {
        operationId: 'readNodeStatus',
        parameters: [
          { name: 'nodeId', in: 'path', required: true, schema: { type: 'string' } },
        ],
        responses: {
          200: {
            description: 'Current node status',
            content: { 'application/json': { schema: { $ref: '#/components/schemas/NodeStatus' } } },
          },
        },
      },
    },
    '/nodes/{nodeId}/commands': {
      post: {
        operationId: 'dispatchNodeCommand',
        parameters: [
          { name: 'nodeId', in: 'path', required: true, schema: { type: 'string' } },
        ],
        requestBody: {
          required: true,
          content: { 'application/json': { schema: { $ref: '#/components/schemas/NodeCommand' } } },
        },
        responses: { 202: { description: 'Command accepted' } },
      },
    },
  },
  components: {
    schemas: {
      NodeStatus: { type: 'object' },
      NodeCommand: { type: 'object' },
    },
  },
});

const sqlBundle = extractCapabilitiesFromSqlDdl(`
CREATE TABLE dialogue_nodes (
  id TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  online BOOLEAN NOT NULL DEFAULT false,
  last_seen_at TIMESTAMPTZ
);

CREATE TABLE dialogue_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  node_id TEXT NOT NULL REFERENCES dialogue_nodes(id),
  event_kind TEXT NOT NULL,
  payload JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
`);

const summary = [schemaBundle, openApiBundle, sqlBundle].map(bundle => ({
  frontend: bundle.frontend,
  sourceRoot: bundle.sourceRoot,
  capabilityCount: bundle.capabilityCount,
  capabilities: bundle.capabilities.map(spec => ({
    id: spec.id,
    operation: spec.operation.name,
    effects: spec.semantics.effects.map(effect => effect.name),
    invariantCount: spec.semantics.invariants.length,
    providerRequired: spec.lowering.providerRequired,
    root: spec.root,
  })),
  diagnostics: bundle.diagnostics,
  root: bundle.root,
}));

console.log(JSON.stringify(summary, null, 2));
