  const runners = {
    posix: 'runners/posix/run.sh',
    windows: 'runners/windows/run.cmd',
    node: 'runners/node/run.mjs',
    termux: 'runners/termux/run.sh',
  };
  writeText(path.join(outputDir, runners.posix), `#!/usr/bin/env sh\nset -eu\nDIR="$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)"\nif [ -x "$DIR/rclvm" ]; then exec "$DIR/rclvm" "$DIR/program.rbc"; fi\nif [ -x "$DIR/native/rclvm" ]; then exec "$DIR/native/rclvm" "$DIR/program.rbc"; fi\nexec rcl native-run "$DIR/program.rbc"\n`, 0o755);
  writeText(path.join(outputDir, runners.windows), `@echo off\nset DIR=%~dp0..\\..\nif exist "%DIR%\\rclvm.exe" "%DIR%\\rclvm.exe" "%DIR%\\program.rbc" & exit /b %ERRORLEVEL%\nif exist "%DIR%\\native\\rclvm.exe" "%DIR%\\native\\rclvm.exe" "%DIR%\\program.rbc" & exit /b %ERRORLEVEL%\nrcl native-run "%DIR%\\program.rbc"\n`, 0o755);
  writeText(path.join(outputDir, runners.node), `#!/usr/bin/env node\nimport { spawnSync } from 'node:child_process';\nimport { dirname, join } from 'node:path';\nimport { fileURLToPath } from 'node:url';\nconst root = dirname(dirname(dirname(fileURLToPath(import.meta.url))));\nconst rbc = join(root, 'program.rbc');\nlet result = spawnSync('rcl', ['native-run', rbc], { stdio: 'inherit' });\nif (result.error) { console.error('Install RCL CLI or run a target-specific entrypoint.'); process.exit(127); }\nprocess.exit(result.status ?? 0);\n`, 0o755);
