export const RCL_PACKAGE_COMPILER_VERSION = '0.24.0-alpha.1';
export const RCL_PACKAGE_TARGETS = Object.freeze(['native-rbc', 'node-cli', 'web-static', 'android-shell', 'rclapp', 'android-apk-seed', 'android-debug-apk', 'rncs-module']);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, '..');
const DEFAULT_PACKAGE_OUTPUT_ROOT = path.join(PROJECT_ROOT, 'output', 'packages');
const SECRET_PATTERNS = [/\.env($|\.)/i, /id_rsa/i, /id_ed25519/i, /\.pem$/i, /\.p12$/i, /\.jks$/i, /keystore/i, /google-services\.json$/i];
const RUNTIME_DIAGNOSTIC_FILES = new Set(['build/android-debug-build-report.json']);

function sha256Bytes(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}

function sha256File(file) {
  return sha256Bytes(fs.readFileSync(file));
}

function slugify(value) {
  return String(value ?? 'rcl-package').replace(/[^a-zA-Z0-9._-]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase() || 'rcl-package';
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function writeText(file, content, mode = undefined) {
  ensureDir(path.dirname(file));
  fs.writeFileSync(file, content);
  if (mode !== undefined) fs.chmodSync(file, mode);
}

function writeJson(file, value) {
  writeText(file, `${JSON.stringify(value, null, 2)}\n`);
}

function copyIfExists(from, to, mode = undefined) {
  if (!fs.existsSync(from)) return false;
  ensureDir(path.dirname(to));
  fs.copyFileSync(from, to);
  if (mode !== undefined) fs.chmodSync(to, mode);
  return true;
}

function manifestRoot(manifest) {
  return realityRoot({ ...manifest, root: undefined });
}

function renderReadme({ target, programName, entrypoints, boundary }) {
  return `# ${programName} — RCL ${target} package\n\nGenerated by RCL Package Compiler v${RCL_PACKAGE_COMPILER_VERSION}.\n\n## Entrypoints\n\n${entrypoints.map(item => `- \`${item}\``).join('\n')}\n\n## Boundary\n\n${boundary}\n`;
}

function escapeHtml(value) {
  return String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function walkFiles(root) {
  const result = [];
  if (!fs.existsSync(root)) return result;
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const full = path.join(root, entry.name);
    if (entry.isDirectory()) result.push(...walkFiles(full));
    else result.push(full);
  }
  return result.sort();
}

function relativeManifestFiles(root) {
  return walkFiles(root)
    .filter(file => !file.endsWith('rcl-package.json'))
    .filter(file => !RUNTIME_DIAGNOSTIC_FILES.has(path.relative(root, file).replaceAll(path.sep, '/')))
    .map(file => ({ path: path.relative(root, file).replaceAll(path.sep, '/'), bytes: fs.statSync(file).size, sha256: sha256File(file) }));
}

function inferHostPermissions(program) {
  const hosts = (program.hosts ?? []).map(host => host.name);
  const warrants = (program.warrants ?? []).map(warrant => `${warrant.capability}@${warrant.target}`);
  const operations = [];
  const androidPermissions = new Set();
  const shellCapabilities = new Set();
  for (const host of hosts) {
    const h = host.toLowerCase();
    if (['network', 'http', 'fetch', 'api'].some(name => h.includes(name))) {
      androidPermissions.add('android.permission.INTERNET');
      shellCapabilities.add('network');
    }
    if (['file', 'fs', 'storage'].some(name => h.includes(name))) {
      shellCapabilities.add('filesystem');
    }
    if (['console', 'terminal', 'shell'].some(name => h.includes(name))) {
      shellCapabilities.add('stdio');
    }
    operations.push({ host, inferred: [...shellCapabilities] });
  }
  return {
    hosts,
    warrants,
    operations,
    androidPermissions: [...androidPermissions].sort(),
    shellCapabilities: [...shellCapabilities].sort(),
    riskLevel: androidPermissions.size || shellCapabilities.has('filesystem') ? 'medium' : 'low',
  };
}

function basePackageContext({ sourcePath, outputDir }) {
  const source = fs.readFileSync(sourcePath, 'utf8');
  const bytecode = compileRealityToBytecode(source);
  const program = compileReality(source);
  const sourceSha256 = sha256Bytes(source);
  const bytecodeSha256 = sha256Bytes(bytecode);
  const programName = program.name;
  const slug = slugify(programName);
  const permissions = inferHostPermissions(program);
  return { source, bytecode, program, programName, slug, sourcePath: path.resolve(sourcePath), outputDir, sourceSha256, bytecodeSha256, permissions };
}

function baseManifest(ctx, target, outputDir) {
  return {
    format: 'rcl.package-manifest.v0.24',
    compiler: 'rcl.package',
    compilerVersion: RCL_PACKAGE_COMPILER_VERSION,
    target,
    program: ctx.programName,
    sourcePath: ctx.sourcePath,
    sourceSha256: ctx.sourceSha256,
    bytecodeSha256: ctx.bytecodeSha256,
    outputDir: path.resolve(outputDir),
    generatedAt: new Date(0).toISOString(),
    requiredRuntime: 'rcl >= 0.24.0-alpha.1',
    capabilities: {
      subjects: ctx.program.subjects ?? [],
      hosts: (ctx.program.hosts ?? []).map(host => host.name),
      warrants: (ctx.program.warrants ?? []).map(warrant => `${warrant.subject}:${warrant.capability}@${warrant.target}`),
      rules: (ctx.program.rules ?? []).map(rule => rule.name),
    },
    security: ctx.permissions,
  };
}

