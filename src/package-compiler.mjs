export function verifyRclPackage(packageDir) {
  const root = path.resolve(packageDir);
  const manifestFile = path.join(root, 'rcl-package.json');
  const diagnostics = [];
  if (!fs.existsSync(manifestFile)) {
    return Object.freeze({ format: 'rcl.package-verification.v0.24', status: 'rejected', packageDir: root, diagnostics: [{ code: 'RCL_PACKAGE_MANIFEST_MISSING', message: 'Missing rcl-package.json' }], root: realityRoot({ status: 'rejected', packageDir: root }) });
  }
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  for (const item of manifest.files ?? []) {
    const file = path.join(root, item.path);
    if (!fs.existsSync(file)) diagnostics.push({ code: 'RCL_PACKAGE_FILE_MISSING', path: item.path });
    else if (sha256File(file) !== item.sha256) diagnostics.push({ code: 'RCL_PACKAGE_FILE_HASH_MISMATCH', path: item.path });
  }
  for (const file of walkFiles(root)) {
    const rel = path.relative(root, file).replaceAll(path.sep, '/');
    if (SECRET_PATTERNS.some(pattern => pattern.test(rel))) diagnostics.push({ code: 'RCL_PACKAGE_SECRET_PATTERN', path: rel });
  }
  const report = { format: 'rcl.package-verification.v0.24', status: diagnostics.length ? 'rejected' : 'verified', packageDir: root, manifestTarget: manifest.target ?? null, program: manifest.program ?? null, fileCount: manifest.files?.length ?? 0, diagnostics };
  return Object.freeze({ ...report, root: realityRoot(report) });
}

export async function packageRclSource(sourcePath, options = {}) {
  const target = options.target ?? 'all';
  if (target !== 'all' && !RCL_PACKAGE_TARGETS.includes(target)) throw new Error(`Unknown RCL package target '${target}'. Expected one of ${RCL_PACKAGE_TARGETS.join(', ')} or all.`);
  const sourceAbs = path.resolve(sourcePath);
  const sourceName = slugify(path.basename(sourceAbs, path.extname(sourceAbs)));
  const outputRoot = path.resolve(options.outputDir ?? path.join(DEFAULT_PACKAGE_OUTPUT_ROOT, `${sourceName}-${target}`));
  const ctx = basePackageContext({ sourcePath: sourceAbs, outputDir: outputRoot });
  const targets = target === 'all' ? RCL_PACKAGE_TARGETS : [target];
  const packages = [];
  ensureDir(outputRoot);
  for (const item of targets) {
    const targetDir = target === 'all' ? path.join(outputRoot, item) : outputRoot;
    packages.push(await TARGET_WRITERS[item](ctx, targetDir));
  }
  const verifications = packages.map(item => verifyRclPackage(item.outputDir));
  const aggregate = {
    format: 'rcl.package-compiler-report.v0.24',
    compilerVersion: RCL_PACKAGE_COMPILER_VERSION,
    program: ctx.programName,
    source: ctx.sourcePath,
    sourceSha256: ctx.sourceSha256,
    bytecodeSha256: ctx.bytecodeSha256,
    target,
    outputRoot,
    packages,
    verifications,
    packageCount: packages.length,
    verifiedPackageCount: verifications.filter(item => item.status === 'verified').length,
    boundary: 'Host-backed hardened package compiler. It emits audited terminal artifacts from RCL source, but the packager itself is not yet RCL-native.',
  };
  const report = { ...aggregate, root: realityRoot(aggregate) };
  writeJson(path.join(outputRoot, 'rcl-package-report.json'), report);
  return Object.freeze(report);
}

