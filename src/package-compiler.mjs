function commandAvailable(command, args = ['--version']) {
  const result = spawnSync(command, args, { encoding: 'utf8', timeout: 5000 });
  return {
    command,
    available: !result.error && (result.status === 0 || result.status === 1),
    status: result.status,
    error: result.error?.message ?? null,
    stdout: (result.stdout ?? '').slice(0, 2000),
    stderr: (result.stderr ?? '').slice(0, 2000),
  };
}

function gradleWrapperFor(projectDir) {
  const name = process.platform === 'win32' ? 'gradlew.bat' : 'gradlew';
  const wrapper = path.join(projectDir, name);
  return fs.existsSync(wrapper) ? wrapper : null;
}

function androidApkCandidates(projectDir) {
  return [
    path.join(projectDir, 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug.apk'),
    path.join(projectDir, 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug-unsigned.apk'),
  ];
}

export function detectAndroidBuildEnvironment(projectDir = process.cwd()) {
  const root = path.resolve(projectDir);
  const wrapper = gradleWrapperFor(root);
  const java = commandAvailable('java', ['-version']);
  const gradle = wrapper ? { command: wrapper, available: true, status: 0, error: null, stdout: '', stderr: 'local gradle wrapper present' } : commandAvailable('gradle', ['--version']);
  const androidHome = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || '';
  const sdkExists = androidHome ? fs.existsSync(androidHome) : false;
  const diagnostics = [];
  if (!java.available) diagnostics.push({ code: 'RCL_ANDROID_JAVA_MISSING', message: 'java is not available on PATH.' });
  if (!gradle.available) diagnostics.push({ code: 'RCL_ANDROID_GRADLE_MISSING', message: 'gradle or gradle wrapper is not available.' });
  if (!androidHome) diagnostics.push({ code: 'RCL_ANDROID_SDK_ENV_MISSING', message: 'ANDROID_HOME or ANDROID_SDK_ROOT is not set.' });
  else if (!sdkExists) diagnostics.push({ code: 'RCL_ANDROID_SDK_PATH_MISSING', message: `Android SDK path does not exist: ${androidHome}` });
  const report = {
    format: 'rcl.android-build-environment.v0.24',
    projectDir: root,
    java,
    gradle,
    gradleWrapper: wrapper,
    androidHome: androidHome || null,
    androidSdkExists: sdkExists,
    canAttemptBuild: java.available && gradle.available && sdkExists,
    diagnostics,
  };
  return Object.freeze({ ...report, status: diagnostics.length ? 'diagnostic-only' : 'buildable', root: realityRoot(report) });
}

export function buildAndroidDebugPackage(packageDir, options = {}) {
  const root = path.resolve(packageDir);
  const environment = detectAndroidBuildEnvironment(root);
  const executeBuild = Boolean(options.executeBuild);
  const reportBase = {
    format: 'rcl.android-debug-build-report.v0.24',
    packageDir: root,
    environment,
    executeBuild,
    apkCandidates: androidApkCandidates(root).map(file => path.relative(root, file).replaceAll(path.sep, '/')),
  };
  let report;
  if (!executeBuild) {
    report = { ...reportBase, status: 'diagnostic-only', apk: null, stdout: '', stderr: '', exitCode: null, boundary: 'Build was not executed. Use rcl package-build-android <package-dir> to attempt Gradle assembleDebug when the Android SDK environment is available.' };
  } else if (!environment.canAttemptBuild) {
    report = { ...reportBase, status: 'environment-missing', apk: null, stdout: '', stderr: '', exitCode: null, boundary: 'Android build environment is incomplete; seed project remains portable.' };
  } else {
    const cmd = environment.gradleWrapper ?? 'gradle';
    const args = ['assembleDebug'];
    const result = spawnSync(cmd, args, { cwd: root, encoding: 'utf8', timeout: options.timeoutMs ?? 120000 });
    const apk = androidApkCandidates(root).find(file => fs.existsSync(file)) ?? null;
    report = {
      ...reportBase,
      status: result.status === 0 && apk ? 'built' : 'failed',
      command: [cmd, ...args].join(' '),
      exitCode: result.status,
      apk: apk ? path.relative(root, apk).replaceAll(path.sep, '/') : null,
      apkSha256: apk ? sha256File(apk) : null,
      stdout: (result.stdout ?? '').slice(-8000),
      stderr: (result.stderr ?? '').slice(-8000),
      boundary: apk ? 'Debug APK was built by the local Android toolchain.' : 'Gradle ran but no debug APK artifact was detected.',
    };
  }
  const rooted = Object.freeze({ ...report, root: realityRoot(report) });
  writeJson(path.join(root, 'build', 'android-debug-build-report.json'), rooted);
  return rooted;
}


