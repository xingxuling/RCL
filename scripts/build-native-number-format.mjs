import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const donor = 'native/gpu-text-runtime/vendor/ryu';
const provenance = JSON.parse(fs.readFileSync(path.join(root, donor, 'PROVENANCE.json'), 'utf8'));
assert.equal(provenance.commit, '4c0618b0e44f7ef027ebae05d2cc7812048f7c8f');

const files = ['common.h', 'digit_table.h', 'd2s_full_table.h', 'd2s_intrinsics.h', 'd2s.c'];
const pieces = files.map(name => {
  const relative = donor + '/' + name;
  const bytes = fs.readFileSync(path.join(root, relative));
  assert.equal(createHash('sha256').update(bytes).digest('hex'),
    provenance.files.find(item => item.path === relative)?.sha256, relative);
  let code = bytes.toString('utf8').replaceAll('\r\n', '\n').replace(/^#include "ryu\/[^"]+"\s*$/gmu, '');
  if (name === 'd2s.c') {
    const end = code.indexOf('\nvoid d2s_buffered(');
    assert.ok(end > 0);
    code = code.slice(0, end).replace('int d2s_buffered_n(', 'static int rcl_ryu_double(');
    assert.ok(code.includes('static int rcl_ryu_double('));
  }
  return '\n/* Adapted from Ryu ' + name + '. The original notice follows. */\n' + code;
});

const header = [
  '/* Generated by scripts/build-native-number-format.mjs.',
  ' * Ryu ' + provenance.commit + ', Apache-2.0.',
  ' * License: native/gpu-text-runtime/vendor/ryu/LICENSE-Apache2.',
  ' */',
  '#ifndef RCL_NUMBER_FORMAT_RYU_H',
  '#define RCL_NUMBER_FORMAT_RYU_H',
  '#include <stdbool.h>',
  '#define RYU_ONLY_64_BIT_OPS',
  ...pieces,
  '#undef RYU_ONLY_64_BIT_OPS',
  '#endif',
  '',
].join('\n');
const embedded = '// Generated by scripts/build-native-number-format.mjs.\n'
  + 'export const RCL_NATIVE_NUMBER_FORMAT_HEADER = ' + JSON.stringify(header) + ';\n';
for (const [file, content] of [
  ['native/number_format_ryu.h', header],
  ['src/generated/native-number-format-support.mjs', embedded],
]) {
  const target = path.join(root, file);
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), content, file);
  else fs.writeFileSync(target, content);
}
