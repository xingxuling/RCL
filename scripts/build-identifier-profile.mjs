#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Pin classification independently of Node/ICU on the execution host.
const unicodeVersion = '17.0';
if (process.versions.unicode !== unicodeVersion) throw new Error(`Identifier profile generation requires Unicode ${unicodeVersion}; found ${process.versions.unicode}`);
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
function rangesFor(pattern) {
  const ranges = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (!pattern.test(String.fromCodePoint(cp))) continue;
    const last = ranges.at(-1);
    if (last && cp === last[1] + 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}
const letters = rangesFor(/^\p{L}$/u), numbers = rangesFor(/^\p{N}$/u);
const hex = value => '0x' + value.toString(16);
const jsTable = (name, ranges) => `const ${name} = [\n${ranges.map(pair => '  ' + pair.map(hex).join(', ') + ',').join('\n')}\n];\n`;
const js = `// Generated by scripts/build-identifier-profile.mjs; Unicode ${unicodeVersion} General_Category L/N.
export const IDENTIFIER_PROFILE = 'rcl.identifier-categories.unicode-17.0.v1';
${jsTable('letters', letters)}${jsTable('numbers', numbers)}
function contains(ranges, codepoint) {
  let low = 0, high = ranges.length / 2;
  while (low < high) {
    const middle = (low + high) >>> 1, start = ranges[middle * 2], end = ranges[middle * 2 + 1];
    if (codepoint < start) high = middle;
    else if (codepoint > end) low = middle + 1;
    else return true;
  }
  return false;
}
function scalar(text) {
  if (typeof text !== 'string' || text.length === 0) return -1;
  const cp = text.codePointAt(0);
  return text.length === (cp > 0xffff ? 2 : 1) && !(cp >= 0xd800 && cp <= 0xdfff) ? cp : -1;
}
export function isIdentifierStart(text) {
  const cp = scalar(text);
  return cp === 0x5f || contains(letters, cp);
}
export function isIdentifierPart(text) {
  const cp = scalar(text);
  return cp === 0x5f || contains(letters, cp) || contains(numbers, cp);
}
`;
const cTable = (name, ranges) => `static const uint32_t ${name}[][2] = {\n${ranges.map(pair => '  {' + pair.map(hex).join(', ') + '},').join('\n')}\n};\n`;
const header = `/* Generated by scripts/build-identifier-profile.mjs; Unicode ${unicodeVersion} General_Category L/N. */
#ifndef RCL_IDENTIFIER_PROFILE_H
#define RCL_IDENTIFIER_PROFILE_H
#include <stdint.h>
#include <stddef.h>
${cTable('rcl_identifier_letters', letters)}${cTable('rcl_identifier_numbers', numbers)}
static int rcl_identifier_contains(const uint32_t ranges[][2], size_t count, uint32_t cp) {
  size_t low = 0, high = count;
  while (low < high) {
    size_t middle = low + (high - low) / 2;
    if (cp < ranges[middle][0]) high = middle;
    else if (cp > ranges[middle][1]) low = middle + 1;
    else return 1;
  }
  return 0;
}
static int rcl_identifier_start(uint32_t cp) {
  return cp == 0x5f || rcl_identifier_contains(rcl_identifier_letters, sizeof(rcl_identifier_letters) / sizeof(rcl_identifier_letters[0]), cp);
}
static int rcl_identifier_part(uint32_t cp) {
  return rcl_identifier_start(cp) || rcl_identifier_contains(rcl_identifier_numbers, sizeof(rcl_identifier_numbers) / sizeof(rcl_identifier_numbers[0]), cp);
}
#endif
`;
const embedded = '// Generated by scripts/build-identifier-profile.mjs.\nexport const RCL_NATIVE_VM_CANONICAL_IDENTIFIER_HEADER = ' + JSON.stringify(header) + ';\n';
for (const [relative, content] of [['src/identifier-profile.mjs', js], ['native/identifier_profile.h', header], ['src/generated/native-identifier-support.mjs', embedded]]) {
  const target = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error('Stale identifier profile: ' + relative);
  } else fs.writeFileSync(target, content);
}
console.log(JSON.stringify({ok: true, unicodeVersion, letterRanges: letters.length, numberRanges: numbers.length, checked: process.argv.includes('--check')}));
