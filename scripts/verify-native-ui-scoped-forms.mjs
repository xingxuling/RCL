import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
import { compileRclWebApplication, emitStandaloneRclWebHtml } from '../src/web-application-compiler.mjs';
import { compileRclAndroidApplication, emitNativeAndroidActivity } from '../src/android-application-compiler.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const output = path.join(root, 'output/module-development-20261028/scoped-forms');
fs.mkdirSync(output, { recursive: true });
const source = fs.readFileSync(path.join(root, 'examples/native-ui/scoped-forms.rcl'), 'utf8');
const web = compileRclWebApplication(source, { schema: 'rcl.native-ui.web-target.v0.1' });
const html = emitStandaloneRclWebHtml(web);
fs.writeFileSync(path.join(output, 'scoped-forms.html'), html);
const checks = `
const checks=[];
const check=(name,ok)=>{if(!ok)throw new Error(name);checks.push(name)};
const el=id=>document.querySelector('[data-rcl-node="'+id+'"]');
const fill=(id,value)=>{el(id).value=value;el(id).dispatchEvent(new Event('input',{bubbles:true}))};
const api=window.RCLNativeUI;
el('SaveContact').click();
check('empty_contact_denied',!api.state.contactSaved&&api.trace.length===0);
check('contact_error_visible',el('Email').getAttribute('aria-invalid')==='true');
check('sibling_error_hidden',el('Nickname').getAttribute('aria-invalid')==='false');
fill('Email','alice@example.com');el('SaveContact').click();
check('contact_saved_while_profile_empty',api.state.contactSaved&&!api.state.profileSaved);
check('contact_scope_valid',api.formValidation('ContactForm').valid);
check('global_still_invalid',!api.formValidation().valid);
const count=api.trace.length;el('SaveProfile').click();
check('profile_denied_without_mutation',!api.state.profileSaved&&api.trace.length===count);
check('profile_error_visible',el('Nickname').getAttribute('aria-invalid')==='true');
fill('Nickname','舟舟');el('SaveProfile').click();
check('both_forms_saved',api.state.contactSaved&&api.state.profileSaved&&api.formValidation().valid);
check('errors_cleared',el('Email').getAttribute('aria-invalid')==='false'&&el('Nickname').getAttribute('aria-invalid')==='false');
return {status:'PASS',checks,state:api.state,eventCount:api.trace.length};`;
const harness = `<output id="scope-result"></output><script>try{const result=(function(){${checks}})();document.getElementById('scope-result').textContent=JSON.stringify(result)}catch(error){document.getElementById('scope-result').textContent=JSON.stringify({status:'FAIL',error:String(error)})}</script>`;
const harnessPath = path.join(output, 'browser-check.html');
fs.writeFileSync(harnessPath, html.replace('</body>', harness + '</body>'));
const browser = process.env.RCL_BROWSER ?? ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(fs.existsSync);
if (!browser) throw new Error('RCL_UI_BROWSER_NOT_FOUND');
const run = spawnSync(browser, ['--headless=new', '--disable-gpu', '--no-first-run', '--disable-background-networking', `--user-data-dir=${path.join(output, 'browser-profile')}`, '--virtual-time-budget=1000', '--dump-dom', pathToFileURL(harnessPath).href], { encoding: 'utf8', windowsHide: true, timeout: 30000, maxBuffer: 8 * 1024 * 1024 });
if (run.error) throw run.error;
if (run.status !== 0) throw new Error(`BROWSER_EXIT:${run.status}`);
const match = run.stdout.match(/<output id="scope-result">([\s\S]*?)<\/output>/);
if (!match) throw new Error('BROWSER_RESULT_MISSING');
const browserResult = JSON.parse(match[1].replaceAll('&quot;', '"').replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&'));
const android = compileRclAndroidApplication(source, { schema: 'rcl.native-ui.android-target.v0.1', applicationId: 'com.taowind.rcl.scopedforms' });
const java = emitNativeAndroidActivity(android);
const activity = java.match(/public (?:final )?class (\w+)/)[1];
const javaPath = path.join(output, activity + '.java');
fs.writeFileSync(javaPath, java);
const androidJar = process.env.RCL_ANDROID_JAR ?? path.join(process.env.LOCALAPPDATA ?? '', 'Android/Sdk/platforms/android-35/android.jar');
let androidResult = { status: 'NOT_RUN', reason: 'Android SDK android.jar missing' };
if (fs.existsSync(androidJar)) {
  const compile = spawnSync('javac', ['-encoding', 'UTF-8', '-classpath', androidJar, '-d', path.join(output, 'classes'), javaPath], { encoding: 'utf8', windowsHide: true, timeout: 30000 });
  androidResult = { status: !compile.error && compile.status === 0 ? 'PASS' : 'FAIL', kind: 'javac-against-android-35', exitCode: compile.status, diagnostics: (compile.stderr ?? '') + (compile.error?.message ?? ''), deviceExecution: 'NOT_RUN' };
}
const evidence = { status: browserResult.status === 'PASS' && androidResult.status === 'PASS' ? 'PASS' : 'INCOMPLETE', uiProgramRoot: web.uiProgramRoot, browser: { executable: browser, ...browserResult }, android: androidResult, scope: 'local scoped-form DOM events and generated Activity compilation; no device acceptance or release promotion' };
fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify(evidence, null, 2) + '\n');
console.log(JSON.stringify(evidence, null, 2));
if (evidence.status !== 'PASS') process.exitCode = 1;
